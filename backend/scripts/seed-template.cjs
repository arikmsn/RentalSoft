async function seedTemplate() {
  console.log('=== Seeding System Area Template ===\n');

  await prisma.systemLocalityTemplate.deleteMany({});
  await prisma.systemAreaTemplate.deleteMany({});

  const OPERATIONAL_AREAS = [
    { name: 'צפון', displayOrder: 1 },
    { name: 'השרון', displayOrder: 2 },
    { name: 'מרכז', displayOrder: 3 },
    { name: 'ירושלים ויהודה ושומרון', displayOrder: 4 },
    { name: 'דרום', displayOrder: 5 },
    { name: 'אילת והערבה', displayOrder: 6 },
  ];

  const areaIdMap = {};
  for (const area of OPERATIONAL_AREAS) {
    const created = await prisma.systemAreaTemplate.create({
      data: { name: area.name, displayOrder: area.displayOrder },
    });
    areaIdMap[area.name] = created.id;
  }

  let total = 0;
  const counts = {};

  function assign(areaName, locality) {
    if (!counts[areaName]) counts[areaName] = 0;
    counts[areaName]++;
    total++;
    return prisma.systemLocalityTemplate.create({
      data: {
        name: locality,
        areaId: areaIdMap[areaName],
        excelAreaRaw: '',
      },
    });
  }

  // Excel "צפון" (368 localities): Gush Dan cities go to השרון, rest go to צפון
  const tzfonBatch = [];
  for (const loc of excelTzfon) {
    const area = GUSH_DAN_IN_TZFON.has(loc) ? 'השרון' : 'צפון';
    tzfonBatch.push({ name: loc, areaId: areaIdMap[area], excelAreaRaw: 'צפון' });
    counts[area] = (counts[area] || 0) + 1;
  }

  // Excel "מרכז" (547 localities): classify each
  const markazBatch = [];
  for (const loc of excelMarkaz) {
    let area;
    if (SHARON_LOCALITIES.has(loc)) area = 'השרון';
    else if (YEHUDA_SHOMRON.has(loc)) area = 'יהודה ושומרון';
    else if (JERUSALEM_AND_SURROUNDINGS.has(loc)) area = 'ירושלים והסביבה';
    else area = 'מרכז';
    markazBatch.push({ name: loc, areaId: areaIdMap[area], excelAreaRaw: 'מרכז' });
    counts[area] = (counts[area] || 0) + 1;
  }

  // Excel "החולה ורמת הגולן" (77) -> צפון
  for (const loc of excelGolanHula) {
    counts['צפון'] = (counts['צפון'] || 0) + 1;
  }

  // Excel "עמק בית שאן ובקעת הירדן" (76) -> צפון
  for (const loc of excelJordanValley) {
    counts['צפון'] = (counts['צפון'] || 0) + 1;
  }

  // Excel "אילת ים המלח והערבה" (57) -> אילת והערבה
  for (const loc of excelEilatArava) {
    counts['אילת והערבה'] = (counts['אילת והערבה'] || 0) + 1;
  }

  // Excel "נגב" (51) + "דרום" (140) -> דרום
  for (const loc of excelNeguev) counts['דרום'] = (counts['דרום'] || 0) + 1;
  for (const loc of excelDrom) counts['דרום'] = (counts['דרום'] || 0) + 1;

  // Insert all localities in batches
  const allBatches = [
    ...tzfonBatch,
    ...markazBatch,
    ...[...excelGolanHula].map(l => ({ name: l, areaId: areaIdMap['צפון'], excelAreaRaw: 'החולה ורמת הגולן' })),
    ...[...excelJordanValley].map(l => ({ name: l, areaId: areaIdMap['צפון'], excelAreaRaw: 'עמק בית שאן ובקעת הירדן' })),
    ...[...excelEilatArava].map(l => ({ name: l, areaId: areaIdMap['אילת והערבה'], excelAreaRaw: 'אילת ים המלח והערבה' })),
    ...[...excelNeguev].map(l => ({ name: l, areaId: areaIdMap['דרום'], excelAreaRaw: 'נגב' })),
    ...[...excelDrom].map(l => ({ name: l, areaId: areaIdMap['דרום'], excelAreaRaw: 'דרום' })),
  ];

  while (allBatches.length > 0) {
    await prisma.systemLocalityTemplate.createMany({
      data: allBatches.splice(0, 100),
      skipDuplicates: true,
    });
  }

  console.log('=== Template locality counts by area ===');
  for (const [name, count] of Object.entries(counts)) {
    console.log(`  ${name}: ${count}`);
  }
  console.log(`  Total: ${Object.values(counts).reduce((a, b) => a + b, 0)}`);
}

seedTemplate()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
